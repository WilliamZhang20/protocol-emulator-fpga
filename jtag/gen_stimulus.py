#!/usr/bin/env python3
"""Generate jtag/stimulus.txt: the host-link sequence shared by
testbench/tb_host_link.sv (simulation) and jtag/run_stimulus.tcl (KV260 over
JTAG), so silicon-vs-sim results compare line by line.

Format, one host-link command per line:
    <cmd hex> [<expected uo_out hex>]   # comment
Each command is held on ui_in, then 8'h00 is held, then uo_out is compared
(if an expectation is given). Protocol per ../protocol-emulator/docs/host-link.md.

Usage: python3 jtag/gen_stimulus.py [--bytes N] [--base ADDR] > jtag/stimulus.txt
"""
import argparse

def cmd(c, p=0):
    return ((c & 0xF) << 4) | (p & 0xF)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bytes", type=int, default=64, help="SRAM bytes to write/read back")
    ap.add_argument("--base", type=lambda s: int(s, 0), default=0x3C0)
    a = ap.parse_args()
    assert 0 <= a.base and a.base + a.bytes <= 1024

    out = []
    def emit(c, expect=None, note=""):
        e = f" {expect:02x}" if expect is not None else ""
        out.append(f"{c:02x}{e}" + (f"   # {note}" if note else ""))

    def set_addr(addr):
        emit(cmd(1, addr), note=f"addr {addr:#05x}")
        emit(cmd(2, addr >> 4))
        emit(cmd(3, addr >> 8))

    pattern = [(37 * i + 11) & 0xFF for i in range(a.bytes)]

    out.append("# -- reset state: status {run,halt,txf,rxe,0,0,eop,err}, levels")
    emit(cmd(0xA), 0x10, "status: stopped, rx empty")
    emit(cmd(0xC), 0x40, "levels ch0: rx empty, all 0")

    out.append(f"# -- write {a.bytes} bytes at {a.base:#05x} (address auto-increments)")
    set_addr(a.base)
    for b in pattern:
        emit(cmd(4, b))
        emit(cmd(5, b >> 4), note=f"write {b:02x}")

    out.append("# -- read each byte back (B does not increment the address)")
    for i, b in enumerate(pattern):
        set_addr(a.base + i)
        emit(cmd(0xB), b, "sram readback")

    out.append("# -- TX FIFO channel 0: push 3 bytes, check levels, fill to 8")
    emit(cmd(0xE, 0), note="channel 0")
    for i, b in enumerate([0x55, 0xAA, 0x0F]):
        emit(cmd(6, b)); emit(cmd(7, b >> 4), note=f"push {b:02x}")
    emit(cmd(0xC), 0x58, "levels: tx 3, rx empty")
    for b in range(5):
        emit(cmd(6, b)); emit(cmd(0xF if b == 4 else 7, 0))
    emit(cmd(0xC), 0xF8, "levels: tx full (reads 7), rx empty")
    emit(cmd(0xA), 0x30, "status: tx_full, rx_empty")
    emit(cmd(0xE, 1), note="channel 1")
    emit(cmd(0xC), 0x40, "levels ch1: empty")
    emit(cmd(0xA), 0x10, "status ch1")
    emit(cmd(0xE, 0), note="back to channel 0")

    print("# generated by jtag/gen_stimulus.py " + " ".join(f"--{k} {v}" for k, v in vars(a).items()))
    print("\n".join(out))

if __name__ == "__main__":
    main()
